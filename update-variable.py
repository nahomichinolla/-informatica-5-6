def main():
    # Augmented Assignment Operator
    # x+= y
    score = 10
    score += 10
    print(score)

    # Subtracton Assignent Operator
    # x -=y
    score = 100
    score -= 15
    print(score)

    # Multipication Assignment Operator
    # x *= y
    balance = 10
    balance *= 4
    print(balance)

    #Division Assignment Operator
    # x /= y
    number = 10
    number /= 5
    print(number)

    # Modulus Assignment Operator
    a = 10
    b = 4

    a %= b
    print(a)

if __name__ == "__main__":
    main()
